export async function enqueueAnalyticsReportController(req: AuthRequest, res: Response) {
	try {
		const tenantId = await resolveTenantId(req);
		if (!tenantId) return error(res, 'tenantId is required', 400);
		const parsed = reportSyncSchema.safeParse({ ...req.body, tenantId });
		if (!parsed.success) return error(res, 'Validation failed', 400, parsed.error.flatten());
		const requestId = getRequestId(req);
		await publishAiEvent({
			type: 'ai:report:generate',
			tenantId,
			requestId,
			data: parsed.data,
		});
		res.setHeader('x-request-id', requestId);
		return success(res, { queued: true, requestId }, 'Analytics report job queued');
	} catch (err) {
		return handleAiError(res, err);
	}
}

export async function replayAnalyticsReportController(req: AuthRequest, res: Response) {
	try {
		const tenantId = await resolveTenantId(req);
		if (!tenantId) return error(res, 'tenantId is required', 400);
		const parsed = replayReportSchema.safeParse(req.body);
		if (!parsed.success) return error(res, 'Validation failed', 400, parsed.error.flatten());

		const requestId = parsed.data.requestId?.trim() || getRequestId(req);
		const reportPayload = { ...parsed.data.report, tenantId };
		const reportParsed = reportSyncSchema.safeParse(reportPayload);
		if (!reportParsed.success) return error(res, 'Validation failed', 400, reportParsed.error.flatten());

		await publishAiEvent({
			type: 'ai:report:generate',
			tenantId,
			requestId,
			data: reportParsed.data,
		});
		res.setHeader('x-request-id', requestId);
		return success(res, { replayQueued: true, requestId }, 'Analytics report replay job queued');
	} catch (err) {
		return handleAiError(res, err);
	}
}

export async function getWeeklyReportsController(req: AuthRequest, res: Response) {
	try {
		const tenantId = await resolveTenantId(req);
		if (!tenantId) return error(res, 'tenantId is required', 400);
		const parsed = reportsQuerySchema.safeParse({
			tenantId,
			limit: req.query.limit ? Number(req.query.limit) : undefined,
		});
		if (!parsed.success) return error(res, 'Validation failed', 400, parsed.error.flatten());
		const employeeId = String(req.params.employeeId || '').trim();
		if (!employeeId) return error(res, 'employeeId is required', 400);
		const requestId = getRequestId(req);
		const result = await fetchWeeklyReports({
			tenantId: parsed.data.tenantId,
			employeeId,
			limit: parsed.data.limit,
			requestId,
		});
		res.setHeader('x-request-id', requestId);
		if (result.traceId) res.setHeader('x-ai-trace-id', result.traceId);
		return success(res, result.data, 'Weekly reports fetched from AI server');
	} catch (err) {
		return handleAiError(res, err);
	}
}

